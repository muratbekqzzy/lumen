// Keep the graph engine local so the Universe also works without a CDN connection.
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let licenses = 'Lumen graph layout dependencies. Generated by npm run build:force.\n';
for (const name of ['d3-force', 'd3-dispatch', 'd3-quadtree', 'd3-timer']) {
  licenses += '\n' + name + '\n' + await readFile(path.join(root, 'node_modules', name, 'LICENSE'), 'utf8');
}
await build({
  absWorkingDir: root,
  stdin: { contents: 'export { forceSimulation, forceLink, forceManyBody, forceCollide, forceX, forceY } from "d3-force";', resolveDir: root },
  outfile: path.join(root, 'web/force.js'), bundle: true, format: 'esm', target: 'es2020', minify: true,
  banner: {js: '/*!\n' + licenses + '\n*/'}, legalComments: 'none',
});
console.log('Built local graph engine with dependency license notices.');
