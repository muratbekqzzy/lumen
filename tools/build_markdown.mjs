import {build} from 'esbuild';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let licenses = 'Generated by npm run build:markdown.\n';
for (const name of ['markdown-it', 'linkify-it', 'mdurl', 'uc.micro', 'punycode.js', 'entities']) {
  for (const file of ['LICENSE', 'LICENSE.txt', 'LICENSE-MIT.txt']) {
    try {licenses += '\n' + name + '\n' + await readFile(path.join(root, 'node_modules', name, file), 'utf8');break;} catch {}
  }
}
await build({absWorkingDir:root,entryPoints:['tools/markdown_entry.js'],outfile:'web/markdown.js',bundle:true,format:'iife',target:'es2020',minify:true,legalComments:'inline',banner:{js:'/*!\n'+licenses+'\n*/'}});
console.log('Built offline Markdown renderer.');
